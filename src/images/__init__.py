"""Stage 2: find one or more images for every selected story."""
from __future__ import annotations

import shutil
from pathlib import Path

from ..collector import make_fetcher
from ..context import Ctx
from ..selection import select_stories
from ..summarizer import extract_keywords
from ..utils import log
from .ai_images import fetch_ai_images
from .article_images import fetch_article_images
from .fallback_cards import render_headline_card
from .stock import fetch_stock_images

VALID_MODES = ("article", "stock", "ai", "cards", "auto")


def effective_modes(ctx: Ctx) -> list[str]:
    """The ordered list of image sources to try. Always ends with 'cards'."""
    mode = str(ctx.get("images.image_mode", "auto")).lower()
    if mode not in VALID_MODES:
        log.warning("Unknown image_mode '%s'; using auto", mode)
        mode = "auto"
    order = list(ctx.get("images.auto_order", ["article", "stock", "cards"])) if mode == "auto" else [mode]
    if ctx.monetization_safe:
        if "article" in order:
            log.info("monetization_safe is on: outlet images are not used")
        order = [m for m in order if m in ("stock", "ai", "cards")]
    if "cards" not in order:
        order.append("cards")
    return order


def make_card(ctx: Ctx, story: dict, out_dir: Path) -> dict:
    dest = render_headline_card(
        out_dir / "card.jpg", ctx.work_size, story["title"], story["outlet"], ctx.date,
        ctx.get("video.brand", {}),
    )
    return {
        "kind": "card", "path": str(dest), "source_url": "", "credit": "",
        "license_note": "Generated by this tool from the headline (no third-party image).",
    }


def run_images(ctx: Ctx) -> int:
    """Find images for each selected story. Idempotent; ``--force`` redoes them."""
    stories = select_stories(ctx)
    if not stories:
        log.warning("No stories selected. Run 'collect' first.")
        return 0
    db, fetcher = ctx.db, make_fetcher(ctx)
    modes = effective_modes(ctx)
    keywords: dict[int, list[str]] = {}
    if "stock" in modes:
        need = [s for s in stories if ctx.force or not _has_images(ctx, s)]
        if need:
            try:
                keywords = extract_keywords(ctx, need)
            except Exception as exc:
                log.warning("Keyword extraction failed (%s)", exc)

    done = 0
    for story in stories:
        if _has_images(ctx, story) and not ctx.force:
            continue
        out_dir = ctx.subdir("images", ctx.date, str(story["id"]))
        if ctx.force:
            db.delete_images(story["id"])
            for old in out_dir.glob("*.jpg"):
                old.unlink(missing_ok=True)
        found: list[dict] = []
        for mode in modes:
            try:
                if mode == "article":
                    found = fetch_article_images(ctx, story, fetcher, out_dir)
                elif mode == "stock":
                    found = fetch_stock_images(ctx, story, keywords.get(story["id"], []), fetcher, out_dir)
                elif mode == "ai":
                    found = fetch_ai_images(ctx, story, out_dir)
                elif mode == "cards":
                    found = [make_card(ctx, story, out_dir)]
            except Exception as exc:  # never let one story break the run
                log.warning("  %s images failed for story %s: %s", mode, story["id"], exc)
                found = []
            if found:
                break
        if not found:
            found = [make_card(ctx, story, out_dir)]
        for img in found:
            db.add_image(story["id"], **img)
        done += 1
        log.info("Images for story %s: %s", story["id"], ", ".join(i["kind"] for i in found))
    log.info("Images ready for %d stories", len(stories))
    return done


def _has_images(ctx: Ctx, story: dict) -> bool:
    rows = ctx.db.images_for(story["id"])
    return bool(rows) and all(Path(r["path"]).exists() for r in rows)
