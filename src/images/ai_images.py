"""AI image generation: a placeholder interface (you choose the provider later).

To add a provider, subclass ``AIImageProvider``, implement ``generate`` to return image
bytes for a prompt, register it in ``PROVIDERS`` and set ``images.ai_provider`` in config.yaml.
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from pathlib import Path

from ..utils import log
from .article_images import fit_image


class AIImageProvider(ABC):
    name = "base"

    @abstractmethod
    def generate(self, prompt: str) -> bytes:
        """Return PNG/JPEG bytes for the prompt."""


PROVIDERS: dict[str, type[AIImageProvider]] = {}  # intentionally empty until you pick one


def fetch_ai_images(ctx, story: dict, out_dir: Path) -> list[dict]:
    name = str(ctx.get("images.ai_provider", "")).lower()
    cls = PROVIDERS.get(name)
    if cls is None:
        log.info("  ai: no image provider configured (images.ai_provider is '%s')", name)
        return []
    provider = cls()
    prompt = f"Editorial illustration, no text, no real people, for a news story: {story['title']}"
    try:
        dest = fit_image(provider.generate(prompt), out_dir / "ai_1.jpg", ctx.work_size)
    except Exception as exc:
        log.warning("  ai image failed: %s", exc)
        return []
    return [{
        "kind": "ai", "path": str(dest), "source_url": "", "credit": "AI-generated illustration",
        "license_note": f"AI-generated by {name}; check that provider's terms before commercial use.",
    }]
